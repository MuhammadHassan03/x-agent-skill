"""ocr.py - Original Content Rewards eligibility tracker and ineligible-content linter.

Original Content Rewards replaced Creator Revenue Sharing on 2026-09-08. Rules
encoded here (references/x-rules.md, last checked 2026-10-21):

  * active Premium plan
  * 500 verified followers
  * 500,000 Home Timeline impressions from verified users in the last 90 days,
    replies excluded
  * original content, 18+, a listed country
  * paid every two weeks, $30 minimum
  * ineligible: copied, minimally modified or aggregated content; posts created
    or posted using automated means; posts exclusively about monetisation
    coaching; engagement solicitation ("like and repost if", "follow for more")

X publishes NO per-impression rate. So this tool refuses to estimate earnings
unless you supply your own rate with --rate-per-1000, and it labels the result
as your assumption. The author of this repo is on a free account and has not
tested enrollment: Premium-only behaviour is documented, not tested.

You read your own numbers off your own Creator Studio screen and type them in.
Nothing here is fetched or verified.

Usage
  python ocr.py status --premium yes --verified-followers 310 --impressions-90d 120000
  python ocr.py status ... --age18 yes --country-listed yes
  python ocr.py status ... --estimate --rate-per-1000 0.50 --period-impressions 40000
  python ocr.py lint posts.txt            posts separated by a line of ---
  python ocr.py status ... --json

Exit codes: 0 eligible (status) or clean (lint), 1 not eligible or issues found, 2 bad input.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from typing import Any, Dict, List, Optional

REQ_FOLLOWERS = 500
REQ_IMPRESSIONS = 500_000
MIN_PAYOUT = 30.0

YES = {"yes", "y", "true", "1"}
NO = {"no", "n", "false", "0"}

INELIGIBLE = [
    ("engagement solicitation",
     r"\b(?:like|rt|retweet|repost)\s*(?:and|&|\+|or)\s*(?:like|rt|retweet|repost|follow)\b|\b(?:rt|retweet|repost|like) if\b|"
     r"\bfollow (?:me )?for more\b|\bcomment\s+\W?\w+\W?\s+(?:and|to)\s+(?:get|receive)\b|\btag (?:someone|a friend)\b|\bbookmark this\b|\bshare if\b"),
    ("monetisation coaching",
     r"\b(?:how to|ways to|tips to|secrets? to)\s+(?:make|earn|get paid|monetize|monetise)\b.*\b(?:on x|on twitter|from x|creator|rewards|payout|revenue)\b|"
     r"\b(?:original content rewards|revenue sharing|creator payout|get verified for money)\b"),
    ("automation marker",
     r"\b(?:auto-?post(?:ed)?|automated post|posted by (?:a )?bot|scheduled by ai|generated by (?:chatgpt|gpt|ai|grok|claude))\b|\[auto\]"),
    ("copied or aggregated marker",
     r"^\s*RT @|\bh/t\b|\b(?:credit|source|via|cc)\s*:\s*@|\b(?:thread|post) by @|\bscreenshot (?:of|from) @"),
]
INEL_RES = [(name, re.compile(p, re.I | re.M | re.S)) for name, p in INELIGIBLE]


def yn(v: str) -> Optional[bool]:
    v = v.strip().lower()
    return True if v in YES else False if v in NO else None


def status(premium: Optional[bool], followers: Optional[int], impressions: Optional[int],
           age18: Optional[bool], country: Optional[bool]) -> Dict[str, Any]:
    items: List[Dict[str, Any]] = []

    def add(name: str, ok: Optional[bool], detail: str) -> None:
        items.append({"requirement": name, "met": ok, "detail": detail})

    add("active Premium plan", premium,
        "yes" if premium else "no: enrollment needs an active Premium plan" if premium is False else "not provided")
    if followers is None:
        add("500 verified followers", None, "not provided")
    else:
        add("500 verified followers", followers >= REQ_FOLLOWERS,
            f"{followers:,} / {REQ_FOLLOWERS:,} ({min(100, followers * 100 // REQ_FOLLOWERS)}%)"
            + ("" if followers >= REQ_FOLLOWERS else f", {REQ_FOLLOWERS - followers:,} to go"))
    if impressions is None:
        add("500,000 verified-viewer Home impressions, 90 days, replies excluded", None, "not provided")
    else:
        add("500,000 verified-viewer Home impressions, 90 days, replies excluded", impressions >= REQ_IMPRESSIONS,
            f"{impressions:,} / {REQ_IMPRESSIONS:,} ({min(100, impressions * 100 // REQ_IMPRESSIONS)}%)"
            + ("" if impressions >= REQ_IMPRESSIONS else f", {REQ_IMPRESSIONS - impressions:,} to go"))
    add("18 or older", age18, "yes" if age18 else "no" if age18 is False else "not provided")
    add("listed country", country, "yes" if country else "no" if country is False else "not provided")
    met = [i["met"] for i in items]
    verdict = "ELIGIBLE (on the numbers you gave)" if all(m is True for m in met) else (
        "NOT ELIGIBLE" if any(m is False for m in met) else "UNKNOWN: some inputs missing")
    return {"verdict": verdict, "requirements": items,
            "note": "Original content is also required and cannot be checked by a number. X reviews applications."}


def estimate(rate_per_1000: float, impressions: int, days_in_period: int = 14) -> Dict[str, Any]:
    gross = impressions / 1000.0 * rate_per_1000
    return {"assumption": f"{rate_per_1000} per 1,000 eligible impressions (YOUR rate; X publishes none)",
            "period_impressions": impressions, "estimated_period_payout": round(gross, 2),
            "meets_30_minimum": gross >= MIN_PAYOUT,
            "note": "Payouts are every two weeks with a $30 minimum. This is arithmetic on an assumption, not a forecast."}


def split_posts(text: str) -> List[str]:
    text = text.replace("\r\n", "\n").strip()
    if re.search(r"(?m)^---+\s*$", text):
        return [p.strip() for p in re.split(r"(?m)^---+\s*$", text) if p.strip()]
    return [ln.strip() for ln in text.splitlines() if ln.strip()]


def lint(posts: List[str]) -> List[Dict[str, Any]]:
    out = []
    for i, p in enumerate(posts, 1):
        hits = [name for name, pat in INEL_RES if pat.search(p)]
        if hits:
            out.append({"post": i, "issues": hits, "text": p[:100]})
    return out


def read_input(path: str) -> str:
    data = sys.stdin.buffer.read() if path == "-" else open(path, "rb").read()
    return data.decode("utf-8-sig")


def main(argv: Optional[List[str]] = None) -> int:
    for _stream in (sys.stdout, sys.stderr):
        if hasattr(_stream, "reconfigure"):
            _stream.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="Original Content Rewards tracker and linter.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("status", help="check your numbers against the thresholds")
    s.add_argument("--premium", help="yes or no")
    s.add_argument("--verified-followers", type=int)
    s.add_argument("--impressions-90d", type=int, help="verified-viewer Home Timeline impressions, last 90 days, replies excluded")
    s.add_argument("--age18", help="yes or no")
    s.add_argument("--country-listed", help="yes or no")
    s.add_argument("--estimate", action="store_true", help="estimate a payout (needs --rate-per-1000)")
    s.add_argument("--rate-per-1000", type=float, help="YOUR assumed payout per 1,000 eligible impressions")
    s.add_argument("--period-impressions", type=int, help="eligible impressions in the two-week period")
    s.add_argument("--json", action="store_true")
    l = sub.add_parser("lint", help="flag posts that would be ineligible")
    l.add_argument("input", help="file with posts separated by --- lines, or - for stdin")
    l.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)
    try:
        if args.cmd == "lint":
            posts = split_posts(read_input(args.input))
            if not posts:
                raise ValueError("no posts found")
            found = lint(posts)
            if args.json:
                print(json.dumps({"posts": len(posts), "issues": found}, indent=2, ensure_ascii=False))
            elif not found:
                print(f"{len(posts)} post(s) checked, none matched an ineligibility marker.\n"
                      "This is a pattern check. It cannot tell whether a post is original.")
            else:
                for f in found:
                    print(f"post {f['post']}: {', '.join(f['issues'])}\n    {f['text']}")
                print(f"\n{len(found)} of {len(posts)} post(s) flagged. Fix them or keep them out of the Rewards count.")
            return 1 if found else 0
        premium, age, ctry = [yn(v) if v else None for v in (args.premium, args.age18, args.country_listed)]
        for name, raw, parsed in (("--premium", args.premium, premium), ("--age18", args.age18, age),
                                  ("--country-listed", args.country_listed, ctry)):
            if raw and parsed is None:
                raise ValueError(f"{name} must be yes or no")
        for name, v in (("--verified-followers", args.verified_followers), ("--impressions-90d", args.impressions_90d),
                        ("--period-impressions", args.period_impressions)):
            if v is not None and v < 0:
                raise ValueError(f"{name} cannot be negative")
        if args.estimate:
            if args.rate_per_1000 is None:
                raise ValueError("refusing to estimate earnings: X publishes no per-impression rate. "
                                 "Pass --rate-per-1000 with a rate you supply, and --period-impressions.")
            if args.rate_per_1000 < 0 or args.period_impressions is None:
                raise ValueError("--estimate needs a non-negative --rate-per-1000 and --period-impressions")
    except (OSError, ValueError) as exc:
        print(f"ocr: {exc}", file=sys.stderr)
        return 2
    res = status(premium, args.verified_followers, args.impressions_90d, age, ctry)
    if args.estimate:
        res["estimate"] = estimate(args.rate_per_1000, args.period_impressions)
    if args.json:
        print(json.dumps(res, indent=2, ensure_ascii=False))
    else:
        print(f"\n{res['verdict']}\n" + "-" * 60)
        for r in res["requirements"]:
            mark = "ok  " if r["met"] else "MISS" if r["met"] is False else "?   "
            print(f"  {mark} {r['requirement']}: {r['detail']}")
        print(f"\n  {res['note']}")
        if "estimate" in res:
            e = res["estimate"]
            print(f"\n  ESTIMATE (your assumption): {e['assumption']}\n  {e['period_impressions']:,} impressions -> "
                  f"${e['estimated_period_payout']:,.2f} ({'meets' if e['meets_30_minimum'] else 'below'} the $30 minimum)\n  {e['note']}")
        print("")
    return 0 if res["verdict"].startswith("ELIGIBLE") else 1


if __name__ == "__main__":
    sys.exit(main())
